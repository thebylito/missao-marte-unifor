alter table jogadores add column skin varchar(32) default 'padrao' not null;

create table moedas (
    id bigint generated by default as identity primary key,
    jogador_id bigint not null references jogadores (id),
    origem varchar(20) not null,
    referencia varchar(64) not null,
    valor integer not null,
    registrado_em timestamp(6) with time zone not null,
    constraint uk_moedas_credito unique (jogador_id, origem, referencia)
);
create index ix_moedas_jogador on moedas (jogador_id, origem, registrado_em);

create table bilhetes (
    id bigint generated by default as identity primary key,
    codigo uuid not null unique,
    jogador_id bigint not null references jogadores (id),
    modo varchar(20) not null,
    dificuldade varchar(20) not null,
    emitido_em timestamp(6) with time zone not null,
    valido_ate timestamp(6) with time zone not null,
    estado varchar(20) not null,
    encerrado_em timestamp(6) with time zone,
    partida_id bigint references partidas (id)
);
create index ix_bilhetes_jogador on bilhetes (jogador_id, estado);
create index ix_bilhetes_partida on bilhetes (partida_id);

create table skins_do_jogador (
    id bigint generated by default as identity primary key,
    jogador_id bigint not null references jogadores (id),
    skin varchar(32) not null,
    comprada_em timestamp(6) with time zone not null,
    constraint uk_skins_do_jogador unique (jogador_id, skin)
);
