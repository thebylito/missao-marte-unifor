-- Regras para as próximas migrações (V2__..., V3__...): nunca editar uma migração já aplicada; colunas de enum são
-- varchar(20) sem check (... in ...), porque quem valida o valor é o enum do Java, na entrada da API (DA-40).

create table jogadores (
    id          bigint generated by default as identity primary key,
    criado_em   timestamp(6) with time zone not null,
    nome        varchar(20) not null,
    senha_hash  varchar(100) not null,
    constraint uk_jogadores_nome unique (nome)
);

create table partidas (
    id              bigint generated by default as identity primary key,
    jogador_id      bigint not null,
    resultado       varchar(20) not null,
    dificuldade     varchar(20) not null,
    modo            varchar(20) default 'CLASSICO' not null,
    pontos          integer not null,
    passageiros     integer not null,
    movimentos      integer not null,
    tempo_segundos  bigint not null,
    registrada_em   timestamp(6) with time zone not null,
    constraint fk_partidas_jogador foreign key (jogador_id) references jogadores (id)
);

-- histórico de um jogador, do mais recente para o mais antigo
create index ix_partidas_jogador on partidas (jogador_id, registrada_em);
-- vitórias do ranking, da maior pontuação para a menor
create index ix_partidas_ranking on partidas (resultado, pontos);
